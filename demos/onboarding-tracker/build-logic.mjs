// build-logic.mjs — vendor the onboarding tracker's OWN server code into the demo.
//
//   node demos/onboarding-tracker/build-logic.mjs
//
// The source project (hcs-onboarding-offboarding) is one Code.js bound to the "Staff Onboarding Requests" sheet:
// a 10-minute trigger reads the identity platform's onboarding emails from a Gmail label, parses each into a sheet
// row (or updates the status / discussion log of an existing one), and four endpoints serve the IT + HR dashboard.
// The demo runs that code verbatim; mock.js supplies the sheet and the mailbox.
//
// WHAT IS VENDORED, AND HOW
//   Code.js   NAMED declarations only (function / const), each with the doc comment above it. Left out on purpose:
//             SPREADSHEET_ID, DASHBOARD_URL and SCHOOL_DOMAIN (a real Drive id, deployment URL and domain — mock.js
//             supplies a demo sheet id), the sheet menus, triggers and the one-time maintenance functions.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { aliasStaffNames, aliasPhrases, PHRASE_ALIASES } from '../../tools/staff-aliases.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const SRC = path.resolve(HERE, '../../../hcs-onboarding-offboarding');

export const WANT = ['TAB_NAME', 'GMAIL_LABEL', 'getDashboardData', 'updateChecklistItem', 'COLS', 'processInboundOnboarding',
  'processDiscussionLog', 'parseOnboardingEmail', 'buildRowData', 'findRowById', 'manualOverrideStatus', 'addManualOnboardingRequest'];
// What this script vendors, for tools/scan-portfolio.mjs.
export const VENDORED = [{ dir: SRC, files: [], decls: { 'Code.js': WANT } }];

export const SERVICES = ['SpreadsheetApp', 'GmailApp', 'Session', 'Utilities', 'HtmlService'];
export const EXPORTS = ['getDashboardData', 'updateChecklistItem', 'manualOverrideStatus', 'addManualOnboardingRequest',
  'processInboundOnboarding', 'parseOnboardingEmail', 'findRowById', 'COLS', 'TAB_NAME', 'GMAIL_LABEL'];

/** Top-level declarations: [{name, text}], text = the declaration plus the comment run above it. */
export function declarations(src) {
  const lines = src.split('\n');
  const isComment = (l) => /^\s*(\/\*\*|\/\*|\*|\*\/|\/\/)/.test(l);
  const starts = [];
  lines.forEach((line, i) => {
    const m = /^(?:function\s+([A-Za-z_$][\w$]*)\s*\(|(?:var|const|let)\s+([A-Za-z_$][\w$]*)\s*=)/.exec(line);
    if (!m) return;
    let doc = i;
    while (doc > 0 && isComment(lines[doc - 1])) doc--;
    starts.push({ name: m[1] || m[2], doc, at: i });
  });
  return starts.map((s, k) => {
    const end = k + 1 < starts.length ? starts[k + 1].doc : lines.length;
    return { name: s.name, text: lines.slice(s.doc, end).join('\n').replace(/\s+$/, '') + '\n' };
  });
}

export const source = () => readFileSync(path.join(SRC, 'Code.js'), 'utf8').replace(/\r\n?/g, '\n');

export function buildLogic() {
  const byName = Object.fromEntries(declarations(source()).map((d) => [d.name, d.text]));
  const missing = WANT.filter((n) => !byName[n]);
  if (missing.length) throw new Error('Code.js is missing: ' + missing.join(', '));
  let out = WANT.map((n) => byName[n]).join('\n');
  const DOMAIN = 'harford' + 'christian';
  out = out.replace(new RegExp(DOMAIN + '\\.org', 'gi'), 'example.edu').replace(new RegExp(DOMAIN, 'gi'), 'example');
  out = aliasStaffNames(aliasPhrases(out, PHRASE_ALIASES).text).text;
  return [
    '/* GENERATED by demos/onboarding-tracker/build-logic.mjs — do not edit.',
    "   The onboarding tracker's OWN server code, verbatim: the named declarations of Code.js the dashboard and the",
    '   10-minute email sync need. The real sheet id, deployment URL and domain are left out; mock.js supplies a demo',
    '   sheet and mailbox and binds the Google services. */',
    '(function (global) {',
    '  var ' + SERVICES.join(', ') + ';',
    out,
    '  global.ONBOARD_LOGIC = {',
    '    bind: function (env) { ' + SERVICES.map((s) => `${s} = env.${s};`).join(' ') + ' },',
    ...EXPORTS.map((n, i) => `    ${n}: ${n}${i < EXPORTS.length - 1 ? ',' : ''}`),
    '  };',
    '})(typeof window !== "undefined" ? window : globalThis);',
    ''
  ].join('\n');
}

/** The sheet layout Code.js documents in its header comment ("A  Approval ID   B  Status ..."), as a header row. */
export function documentedHeaders() {
  const block = /Sheet columns \(Onboarding_Log\):([\s\S]*?)\*\//.exec(source())[1];
  const cols = {};
  for (const m of block.matchAll(/\b([A-Y])\s{2}(\S.*?)(?=\s{2,}[A-Y]\s{2}|\s*\n|$)/g)) cols[m[1]] = m[2].trim();
  return 'ABCDEFGHIJKLMNOPQRSTUVWXY'.split('').map((c) => cols[c]);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (!existsSync(SRC)) { console.log('SKIP build-logic: source project not found at', SRC); process.exit(0); }
  const out = buildLogic();
  writeFileSync(path.join(HERE, 'logic.js'), out);
  console.log('built demos/onboarding-tracker/logic.js (' + out.length + ' bytes)');
}
