// build-kiosk-logic.mjs — vendor the Ramp Kiosk's SERVER into the demo, verbatim.
//
//   node demos/transportation/build-kiosk-logic.mjs
//
// The Ramp Kiosk (FACTS/transportation-kiosk) is a separate Apps Script project: a read-only window onto
// Dismissal_RAMP_BOARD.json, the file this demo's Dismissal server already publishes into mock.js's Drive
// folder (dsPublishBundle_ -> dsWriteRampFile_). kiosk.html is the kiosk's real page (Kiosk.html, with the
// generated KioskClient = Pure.gs inlined by build-demo.mjs); this script writes kiosk-logic.js, which the
// page loads in <head>, in two parts:
//
//   1. ../transportation/DismissalClient.html's script, as page globals — the PUBLISHER's pure logic. In
//      production the minute publisher runs in the dismissal project; in the demo it runs in the kiosk's
//      tab (mock.js calls the vendored publishBoardTick from logic.js), and logic.js resolves dsBuildBoard,
//      dsRampSlice and the rest as page globals, exactly as board.html supplies them.
//   2. The kiosk's Config.gs and Code.gs WHOLE, inside an IIFE with its own Google services (it is its own
//      project: its own Script Properties, an anonymous visitor), exported as window.KIOSK_LOGIC. mock.js
//      binds it to the SAME in-memory Drive folder the Dismissal server writes into, so rampApi and doGet
//      read the very file the publisher wrote. Pure.gs is not here — the page inlines it as KioskClient.
//
// Scrubs: the same as build-logic.mjs (scrubVendored): the real domain, the deployment URL, the shared
// folder's Drive id, and the people named in comments via the hashed alias tables.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { SRC as DISMISSAL_SRC, scrubVendored } from './build-logic.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const KIOSK_SRC = path.resolve(HERE, '../../../FACTS/transportation-kiosk');
export const KIOSK_SERVICES = ['DriveApp', 'PropertiesService', 'HtmlService', 'ScriptApp', 'Session', 'Utilities', 'Logger'];
export const KIOSK_EXPORTS = ['doGet', 'rampApi', 'readRampBoard_', 'getRampFileId_', 'isKioskEnabled_', 'isValidToken_', 'kioskTokens_',
  'getFullAppUrl_', 'RAMP_BOARD_FILE', 'PROP_RAMP_FILE_ID', 'PROP_KIOSK_TOKENS', 'PROP_KIOSK_ENABLED', 'PROP_FULL_APP_URL'];

const lf = (s) => s.replace(/\r\n?/g, '\n');

/** DismissalClient.html minus its <script> wrapper: the generated, comment-stripped Dismissal.gs. */
export function dismissalClientScript() {
  const html = lf(readFileSync(path.join(DISMISSAL_SRC, 'DismissalClient.html'), 'utf8'));
  const m = /^<script>\n([\s\S]*)<\/script>\n?$/.exec(html);
  if (!m) throw new Error('DismissalClient.html is not a single <script> block');
  return m[1];
}

export function buildKioskLogic() {
  const pure = scrubVendored(dismissalClientScript());
  let server = '';
  for (const f of ['Config.gs', 'Code.gs']) server += `\n/* ===== transportation-kiosk/${f} ===== */\n` + lf(readFileSync(path.join(KIOSK_SRC, f), 'utf8'));
  server = scrubVendored(server);
  return [
    '/* GENERATED by demos/transportation/build-kiosk-logic.mjs — do not edit.',
    '   Part 1: ../transportation/DismissalClient.html (the publisher\'s pure logic, generated from Dismissal.gs),',
    '   as page globals for the vendored minute publisher in logic.js. Part 2: the Ramp Kiosk\'s own server,',
    '   Config.gs and Code.gs whole (ids scrubbed), as window.KIOSK_LOGIC; mock.js binds its Google services. */',
    '/* ===== ../transportation/DismissalClient.html ===== */',
    pure.replace(/\s+$/, ''),
    '',
    '(function (global) {',
    '  var ' + KIOSK_SERVICES.join(', ') + ';',
    server,
    '  global.KIOSK_LOGIC = {',
    '    bind: function (env) { ' + KIOSK_SERVICES.map((s) => `${s} = env.${s};`).join(' ') + ' },',
    ...KIOSK_EXPORTS.map((n, i) => `    ${n}: ${n}${i < KIOSK_EXPORTS.length - 1 ? ',' : ''}`),
    '  };',
    '})(typeof window !== "undefined" ? window : globalThis);',
    ''
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (!existsSync(KIOSK_SRC)) { console.log('SKIP build-kiosk-logic: source project not found at', KIOSK_SRC); process.exit(0); }
  const out = buildKioskLogic();
  writeFileSync(path.join(HERE, 'kiosk-logic.js'), out);
  console.log('built demos/transportation/kiosk-logic.js (' + out.length + ' bytes)');
}
